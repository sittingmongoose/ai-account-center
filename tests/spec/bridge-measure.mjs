/**
 * L1 measurement under Node (the installed runtime): end-to-end request time of the real dashboard
 * server with the Rust service off and on, in alternating rounds (ABAB: 5 rounds of 40 samples per
 * route), so drift on a loaded host cancels; the load average before and after every round; a
 * concurrency row (16 clients for 60 s: p50, p95, p99 and the server's event-loop p99); RSS of TS and
 * of the Rust child; and, for builds that have the L1 hooks, the paired timings a shadow server
 * records on the same requests (TS path vs Rust path). Optionally one heap attribution of the TS
 * process on the large home (never a live process).
 *
 * It measures a given build, so the same driver measures before and after:
 *   node tests/spec/bridge-measure.mjs --dist <dist> --binary <aac-http> --out <file.json>
 *        [--rounds 5] [--samples 40] [--clients 16] [--seconds 60] [--shadow] [--heap]
 *        [--label <text>]
 * The fixture home is generated by large-home.mjs into a scratch folder and removed afterwards.
 */
import assert from 'node:assert/strict';
import { fork, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import http from 'node:http';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const option = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : fallback;
};
const flag = (name) => args.includes(`--${name}`);
const dist = path.resolve(option('dist', path.join(here, '../../dist')));
const binary = path.resolve(option('binary', path.join(dist, 'native/aac-http')));
const out = option('out', null);
const rounds = Number(option('rounds', 5));
const samples = Number(option('samples', 40));
const clients = Number(option('clients', 16));
const seconds = Number(option('seconds', 60));
assert.ok(out, '--out <file.json> is required');
assert.ok(fs.existsSync(path.join(dist, 'web-server/index.js')), `no built server in ${dist}`);
assert.ok(fs.existsSync(binary), `no aac-http at ${binary}`);

const ROUTES = [
  { path: '/api/health', signedIn: false },
  { path: '/api/accounts/settings', signedIn: true },
  { path: '/api/accounts/visibility', signedIn: true },
  { path: '/api/accounts/preferences', signedIn: true },
  { path: '/api/claude/desktop-profiles', signedIn: true },
];
const scratch = fs.mkdtempSync(path.join(process.env.TMPDIR ?? os.tmpdir(), 'aac-l1-measure-'));
const workers = [];

function home(name) {
  const root = path.join(scratch, name);
  const made = spawnSync(process.execPath, [path.join(here, 'large-home.mjs'), root], {
    encoding: 'utf8',
  });
  assert.equal(made.status, 0, made.stderr);
  return { root, summary: JSON.parse(made.stdout) };
}

function start(mode, root) {
  return new Promise((resolve, reject) => {
    const child = fork(path.join(here, 'bridge-measure-server.cjs'), [dist, binary, mode, root], {
      execArgv: ['--expose-gc'],
      stdio: ['ignore', 'ignore', 'pipe', 'ipc'],
    });
    let stderr = '';
    child.stderr.on('data', (d) => (stderr += d));
    const worker = { mode, child, pending: [] };
    workers.push(worker);
    child.on('message', (message) => {
      if (message.type === 'ready') {
        worker.port = message.port;
        resolve(worker);
      } else if (message.type === 'error') reject(new Error(message.message));
      else worker.pending.shift()?.(message);
    });
    child.once('exit', (code) => {
      if (!worker.port) reject(new Error(`worker ${mode} exited ${code}: ${stderr.slice(-2000)}`));
    });
  });
}

function ask(worker, message) {
  return new Promise((resolve) => {
    worker.pending.push(resolve);
    worker.child.send(message);
  });
}

const agent = new http.Agent({ keepAlive: true, maxSockets: 64 });
function call(worker, route, cookie, method = 'GET', body = undefined) {
  return new Promise((resolve, reject) => {
    const started = performance.now();
    const request = http.request(
      {
        host: '127.0.0.1',
        port: worker.port,
        path: route,
        method,
        agent,
        headers: {
          origin: `http://127.0.0.1:${worker.port}`,
          ...(cookie ? { cookie } : {}),
          ...(body ? { 'content-type': 'application/json' } : {}),
        },
      },
      (response) => {
        const chunks = [];
        response.on('data', (c) => chunks.push(c));
        response.on('end', () =>
          resolve({
            status: response.statusCode,
            ms: performance.now() - started,
            body: Buffer.concat(chunks).toString('utf8'),
            headers: response.headers,
          })
        );
      }
    );
    request.on('error', reject);
    request.end(body);
  });
}

async function login(worker) {
  const reply = await call(
    worker,
    '/api/auth/login',
    null,
    'POST',
    JSON.stringify({ username: 'fixture-admin', password: 'fixture-password-only' })
  );
  assert.equal(reply.status, 200, reply.body);
  worker.cookie = String(reply.headers['set-cookie']).split(';')[0];
}

const summarize = (values) => {
  const sorted = [...values].sort((a, b) => a - b);
  const at = (q) => sorted[Math.min(sorted.length - 1, Math.max(0, Math.ceil(sorted.length * q) - 1))];
  const r = (v) => Math.round(v * 1000) / 1000;
  return sorted.length
    ? { samples: sorted.length, p50Ms: r(at(0.5)), p95Ms: r(at(0.95)), p99Ms: r(at(0.99)) }
    : { samples: 0 };
};

try {
  const fixture = home('off');
  home('on');
  const off = await start('off', path.join(scratch, 'off'));
  const on = await start('on', path.join(scratch, 'on'));
  const pair = [off, on];
  for (const worker of pair) await login(worker);
  // Same answers from both servers (the bodies are the goldens' business; here: status and size).
  for (const route of ROUTES) {
    const a = await call(off, route.path, route.signedIn ? off.cookie : null);
    const b = await call(on, route.path, route.signedIn ? on.cookie : null);
    assert.equal(a.status, 200, `${route.path} off: ${a.body.slice(0, 200)}`);
    assert.equal(b.status, 200, `${route.path} on: ${b.body.slice(0, 200)}`);
    assert.equal(a.body, b.body, `${route.path}: off and on answer the same bytes`);
  }
  // Warm both.
  for (const worker of pair)
    for (const route of ROUTES)
      for (let i = 0; i < 20; i++) await call(worker, route.path, route.signedIn ? worker.cookie : null);
  for (const worker of pair) await ask(worker, { type: 'stats', reset: true });

  const latency = Object.fromEntries(pair.map((w) => [w.mode, Object.fromEntries(ROUTES.map((r) => [r.path, []]))]));
  const roundLog = [];
  for (let round = 0; round < rounds; round++)
    for (const worker of pair) {
      const loadBefore = os.loadavg();
      for (const route of ROUTES)
        for (let i = 0; i < samples; i++)
          latency[worker.mode][route.path].push(
            (await call(worker, route.path, route.signedIn ? worker.cookie : null)).ms
          );
      roundLog.push({ round: round + 1, mode: worker.mode, loadBefore, loadAfter: os.loadavg() });
    }
  const memory = {};
  for (const worker of pair) memory[worker.mode] = await ask(worker, { type: 'stats', reset: true });

  // The concurrency row: 16 clients for 60 s over the signed-in routes.
  const concurrency = {};
  for (const worker of pair) {
    await ask(worker, { type: 'stats', reset: true });
    const loadBefore = os.loadavg();
    const end = Date.now() + seconds * 1000;
    const times = [];
    let errors = 0;
    await Promise.all(
      Array.from({ length: clients }, async (_, c) => {
        let i = c;
        while (Date.now() < end) {
          const route = ROUTES[1 + (i++ % (ROUTES.length - 1))];
          const reply = await call(worker, route.path, worker.cookie);
          if (reply.status === 200) times.push(reply.ms);
          else errors++;
        }
      })
    );
    const stats = await ask(worker, { type: 'stats', reset: true });
    concurrency[worker.mode] = {
      clients,
      seconds,
      requests: times.length,
      errors,
      ...summarize(times),
      eventLoopP99Ms: Math.round(stats.eventLoop.p99Ms * 1000) / 1000,
      tsRssBytes: stats.tsRssBytes,
      rustRssBytes: stats.rustRssBytes,
      loadBefore,
      loadAfter: os.loadavg(),
      bridge: stats.bridge,
    };
  }

  // Paired timings on the same requests, from a shadow server (L1 builds only).
  let paired = null;
  if (flag('shadow')) {
    home('shadow');
    const shadow = await start('shadow', path.join(scratch, 'shadow'));
    await login(shadow);
    for (let i = 0; i < 200; i++)
      for (const route of ROUTES)
        await call(shadow, route.path, route.signedIn ? shadow.cookie : null);
    await new Promise((r) => setTimeout(r, 500));
    const stats = await ask(shadow, { type: 'stats' });
    paired = stats.diagnostics
      ? Object.fromEntries(
          Object.entries(stats.diagnostics.routes).map(([route, r]) => [
            route,
            { equal: r.equal, different: r.different, skipped: r.skipped, declined: r.declined, failed: r.failed, paired: r.paired },
          ])
        )
      : 'this build has no paired-timing hooks';
  }

  // One heap attribution of the TS process on the large home: the same server with the Status
  // and Scoreboard owners running on the fixture share, against the baseline with them stubbed.
  // The difference is what moving those owners can free from the TS heap (design section 0).
  let heap = null;
  if (flag('heap')) {
    home('owners');
    const withOwners = await start('off+owners', path.join(scratch, 'owners'));
    await login(withOwners);
    // Let the readers scan the share, then build both views a few times.
    await new Promise((r) => setTimeout(r, 15_000));
    const views = {};
    for (const route of ['/api/status', '/api/scoreboard']) {
      let reply;
      for (let i = 0; i < 5; i++) reply = await call(withOwners, route, withOwners.cookie);
      views[route] = { status: reply.status, bytes: reply.body.length };
    }
    const attribute = async (worker, name) => {
      const file = path.join(scratch, `${name}.heapsnapshot`);
      await ask(worker, { type: 'heap', file });
      const stats = await ask(worker, { type: 'stats' });
      const snapshot = JSON.parse(fs.readFileSync(file, 'utf8'));
      fs.rmSync(file, { force: true });
      const fields = snapshot.snapshot.meta.node_fields;
      const width = fields.length;
      const nameAt = fields.indexOf('name');
      const sizeAt = fields.indexOf('self_size');
      const typeAt = fields.indexOf('type');
      const types = snapshot.snapshot.meta.node_types[0];
      const totals = new Map();
      let total = 0;
      for (let i = 0; i < snapshot.nodes.length; i += width) {
        const type = types[snapshot.nodes[i + typeAt]];
        const label =
          type === 'object' || type === 'closure'
            ? snapshot.strings[snapshot.nodes[i + nameAt]]
            : `(${type})`;
        const size = snapshot.nodes[i + sizeAt];
        total += size;
        totals.set(label, (totals.get(label) ?? 0) + size);
      }
      return { total, totals, rss: stats.tsRssBytes };
    };
    const base = await attribute(off, 'baseline');
    const loaded = await attribute(withOwners, 'owners');
    heap = {
      views,
      baseline: { heapSelfBytes: base.total, tsRssBytes: base.rss },
      withOwners: { heapSelfBytes: loaded.total, tsRssBytes: loaded.rss },
      ownersHoldBytes: loaded.total - base.total,
      topDifferences: [...loaded.totals]
        .map(([name, bytes]) => ({ name, bytes: bytes - (base.totals.get(name) ?? 0) }))
        .sort((a, b) => b.bytes - a.bytes)
        .slice(0, 15),
    };
  }

  const report = {
    label: option('label', null),
    node: process.version,
    host: os.hostname(),
    cpus: os.cpus().length,
    dist,
    binarySha256: (await import('node:crypto')).createHash('sha256').update(fs.readFileSync(binary)).digest('hex'),
    fixture: fixture.summary,
    roundCount: rounds,
    samplesPerRound: samples,
    latency: Object.fromEntries(
      Object.entries(latency).map(([mode, routes]) => [
        mode,
        Object.fromEntries(Object.entries(routes).map(([route, values]) => [route, summarize(values)])),
      ])
    ),
    onMinusOffP50Ms: Object.fromEntries(
      ROUTES.map((r) => [
        r.path,
        Math.round((summarize(latency.on[r.path]).p50Ms - summarize(latency.off[r.path]).p50Ms) * 1000) / 1000,
      ])
    ),
    memory: Object.fromEntries(
      Object.entries(memory).map(([mode, m]) => [
        mode,
        { tsRssBytes: m.tsRssBytes, heapUsedBytes: m.heapUsedBytes, rustRssBytes: m.rustRssBytes, bridge: m.bridge },
      ])
    ),
    concurrency,
    paired,
    heap,
    roundLog,
  };
  fs.writeFileSync(out, JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify({ onMinusOffP50Ms: report.onMinusOffP50Ms, served: memory.on.bridge }, null, 0));
} finally {
  for (const worker of workers) {
    try {
      worker.child.send({ type: 'stop' });
    } catch {
      /* Already gone. */
    }
  }
  await new Promise((r) => setTimeout(r, 1500));
  for (const worker of workers) if (worker.child.exitCode === null) worker.child.kill('SIGKILL');
  agent.destroy();
  fs.rmSync(scratch, { recursive: true, force: true });
}
